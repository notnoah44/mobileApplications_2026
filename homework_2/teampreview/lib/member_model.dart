class TeamMember {
  final String firstName;
  final String imagePath;
  final String quote;
  final String homeCountry;
  final String role;
  final List<String> hobbies;

  TeamMember({
    required this.firstName,
    required this.imagePath,
    required this.quote,
    required this.homeCountry,
    required this.role,
    required this.hobbies,
  });
}
